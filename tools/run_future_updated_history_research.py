"""Future-only generic research runner, not the official Reference/Stage B.
Train strict and legacy input comparators using same updated outcomes.
No live card generated by tests; explicit verified lineup required.
"""
from datetime import date,datetime,timezone
from pathlib import Path
import json,hashlib,argparse
from wshlx_ufc.postevent_history_extension_v1 import load_extended_records
from wshlx_ufc.strict_history_inputs_v1 import strict_records,matrices_from_records
from wshlx_ufc.prefight_finish_resistance import build_from_records
from wshlx_ufc.prefight_opponent_quality import build_historical_opponent_quality
from wshlx_ufc.winner_recent_form_v3 import construct_record_history
from wshlx_ufc.historical_feature_matrix import RESISTANCE,QUALITY
from wshlx_ufc.finish_v1_research import coherent_six,METHODS
from benchmark_strict_history_v1 import train,predict
from lock_ufcqatar_winner_v3_research import align_to_source
import numpy as np

def query(records,cutoff,pairs):
    r,_=build_from_records(records,as_of_exclusive=cutoff,query_bouts=pairs)
    rq=[x for x in r if x.get("query_only")]
    hist=[{"date":x["date"].isoformat(),"event":x["event"],"a":x["a"],"b":x["b"],"outcome":"/".join(x["result"])} for x in records]
    qq=[x for x in build_historical_opponent_quality(hist,query_date=cutoff,query_bouts=pairs) if x.get("query_only")]
    form=construct_record_history(records,cutoff=cutoff,query_date=cutoff,query_bouts=tuple(pairs))
    if len(rq)!=len(qq) or len(rq)!=len(pairs):raise ValueError("query length mismatch")
    out=[];forms={}
    for i,(a,b) in enumerate(pairs):
        x,y=rq[i],qq[i]
        if (x["a"],x["b"])!=(a,b) or (y["a"],y["b"])!=(a,b):raise ValueError("query identity mismatch")
        f={"bout_id":f"future_{i}","event_date":cutoff,"feature_as_of_exclusive":cutoff,"fighter_a":a,"fighter_b":b}
        for fields,row in ((RESISTANCE,x),(QUALITY,y)):
            for k in fields:
                for side in ("a","b"):f[side+"_"+k]=row[side+"_pre"][k]
        for side in ("a","b"):
            if f[side+"_prior_ufc_bouts"]!=f[side+"_ufc_prior_bouts"]:raise ValueError("prior counts disagree")
        z=form[(cutoff,"__PREFIGHT_QUERY_NO_RESULTS__",*sorted((a,b)))]
        if not z.get("query_only") or (z["a_name"],z["b_name"])!=(a,b):raise ValueError("form mismatch")
        forms[f["bout_id"]]=(z["a"],z["b"]);out.append(f)
    return out,forms

def build(lineup,*,now,secondary=False):
    cutoff=lineup["event_date"]
    first=datetime.fromisoformat(lineup["first_fight_utc"].replace("Z","+00:00"))
    if now.tzinfo is None or first.tzinfo is None or now>=first or date.fromisoformat(cutoff)<=now.date():
        raise ValueError("Requires a strictly future event and pre-event timestamp")
    if not lineup.get("lineup_source_url","").startswith("https://") or lineup.get("lineup_verified_by_caller") is not True:
        raise ValueError("Provide externally checked upcoming lineup and source reference")
    fights=lineup["fights"]
    if not 1<=len(fights)<=20 or any(not x.get("a") or not x.get("b") for x in fights):raise ValueError("invalid lineup")
    if any(set(x)-{"a","b","provisional"} for x in fights):raise ValueError("lineup must not contain result or odds fields")
    records,audit=load_extended_records(as_of_exclusive=cutoff,allow_secondary_qatar_stats=secondary)
    strict,qa=strict_records(records)
    names=[x[s] for x in fights for s in ("a","b")]
    resolved,identity=align_to_source(names,records)
    pairs=[tuple(resolved[i:i+2]) for i in range(0,len(resolved),2)]
    rows=[{"a":f["a"],"b":f["b"],"provisional":bool(f.get("provisional")),
          "identity_a":identity[2*i],"identity_b":identity[2*i+1],"models":{},
          "research_only":True,"not_an_approved_wager":True} for i,f in enumerate(fights)]
    counts={}
    for name,rec in (("legacy_updated_v3",records),("strict_updated_v3",strict)):
        m=matrices_from_records(rec,cutoff)
        fit=train(*m,cutoff)
        counts[name]=fit[2]
        ff,form=query(rec,cutoff,pairs)
        for i,f in enumerate(ff):
            p,c=predict(f,form,fit);q=coherent_six(p,c)
            side=0 if p>=.5-1e-12 else 1
            idx=3*side+int(np.argmax(q[3*side:3*side+3]))
            rows[i]["models"][name]={"p_a":p,"winner":rows[i]["a" if side==0 else "b"],
              "method":METHODS[idx%3],"p_exact":float(q[idx]),
              "six_joint":dict(zip(("A_KO","A_SUB","A_DEC","B_KO","B_SUB","B_DEC"),map(float,q))),
              "a_prior_bouts":f["a_prior_ufc_bouts"],"b_prior_bouts":f["b_prior_ufc_bouts"],
              "a_stats_coverage":f["a_stats_coverage"],"b_stats_coverage":f["b_stats_coverage"]}
    if set(counts.values())!={3039}:raise ValueError("Unexpected updated training count")
    return {"schema":"WSHLX_GENERIC_UPDATED_HISTORY_SHADOW_V1","event_date":cutoff,
            "first_fight_utc":first.isoformat(),"generated_utc":now.isoformat(),
            "lineup_source_url":lineup["lineup_source_url"],"training_counts":counts,
            "history_audit":audit,"strict_audit":qa,"fights":rows,
            "source_through":"2026-11-21","research_only":True,"no_model_promotion":True,
            "no_odds_used":True,"new_approved_bets":0}

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--lineup",type=Path,required=True)
    ap.add_argument("--output",type=Path,required=True)
    ap.add_argument("--allow-secondary-qatar-stats",action="store_true")
    a=ap.parse_args()
    if a.output.exists():raise FileExistsError("Never overwrite research output")
    raw=a.lineup.read_bytes()
    report=build(json.loads(raw),now=datetime.now(timezone.utc),secondary=a.allow_secondary_qatar_stats)
    if datetime.now(timezone.utc)>=datetime.fromisoformat(report["first_fight_utc"]):raise ValueError("Event began during fit")
    report["lineup_sha256"]=hashlib.sha256(raw).hexdigest()
    a.output.parent.mkdir(parents=True,exist_ok=True)
    with a.output.open("x") as f:json.dump(report,f,indent=2,allow_nan=False)
if __name__=="__main__":main()
